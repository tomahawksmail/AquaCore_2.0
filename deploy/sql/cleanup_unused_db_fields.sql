-- OPTIONAL, EXPLICIT MAINTENANCE ONLY; never executed at application startup.
-- Run on the existing AquaCore MariaDB instance AFTER a verified backup.
-- Stop web, scheduler, sensor and system collectors first; check safe relay state.
-- This script deletes only legacy all-zero synthetic samples and drops only the
-- eight no-longer-used psutil columns whose existing values are ALL NULL/zero.
-- Nonzero legacy values are kept for manual investigation.
-- It never touches the active calibration, WiFi, status, users or pumps;
-- historical temperature and TDS are preserved.
USE `_AquaCore_`;

SELECT 'synthetic_sensor_zero_rows' AS item, COUNT(*) AS candidates
FROM `data` WHERE `temp` <=> 0 AND `ph` <=> 0 AND `tds` <=> 0;
SELECT 'synthetic_system_zero_rows' AS item, COUNT(*) AS candidates
FROM `psutil`
WHERE `RAM_total` <=> 0 AND `RAM_available` <=> 0
  AND `RAM_used` <=> 0 AND `scpufreq_cur` <=> 0;

-- Historical pH values collected under the now-deleted temporary/three-buffer
-- calculations should not be reused as current calibrated pH. Clear only
-- obsolete pH cells, preserving their original timestamps, temperature and TDS.
SELECT COUNT(*) AS obsolete_old_curve_ph_cells FROM `data`
 WHERE `ph` IS NOT NULL
   AND `Datetime` < (SELECT `ph_updated_at` FROM `sensor_calibration` WHERE id=1);
UPDATE `data` SET `ph`=NULL
 WHERE `ph` IS NOT NULL
   AND `Datetime` < (SELECT `ph_updated_at` FROM `sensor_calibration` WHERE id=1);
SELECT ROW_COUNT() AS cleared_old_curve_ph_cells;

-- Historically generated by scheduler.insert_missing_*_zeros().
-- All three sensor metrics zero simultaneously are not a valid water sample.
DELETE FROM `data` WHERE `temp` <=> 0 AND `ph` <=> 0 AND `tds` <=> 0;
SELECT ROW_COUNT() AS removed_synthetic_sensor_rows;

-- Old watchdog inserted system metrics as zeros; new dashboard no longer
-- requires such rows to distinguish an offline collector.
DELETE FROM `psutil`
WHERE `RAM_total` <=> 0 AND `RAM_available` <=> 0
  AND `RAM_used` <=> 0 AND `scpufreq_cur` <=> 0;
SELECT ROW_COUNT() AS removed_synthetic_system_rows;

DROP PROCEDURE IF EXISTS `aquacore_drop_unused_psutil_if_empty`;
DELIMITER //
CREATE PROCEDURE `aquacore_drop_unused_psutil_if_empty`(IN col VARCHAR(64))
BEGIN
  DECLARE present_count INT DEFAULT 0;
  IF col NOT IN ('scpufreq_min','scpufreq_max','cpu_thermal_high',
                 'cpu_thermal_crit','gpu_thermal_cur','gpu_thermal_high',
                 'gpu_thermal_crit','ve_thermal_cur') THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Column not on audited allowlist';
  END IF;

  SELECT COUNT(*) INTO present_count
    FROM information_schema.COLUMNS
   WHERE TABLE_SCHEMA=DATABASE() AND TABLE_NAME='psutil' AND COLUMN_NAME=col;
  IF present_count > 0 THEN
    SET @aquacore_meaningful = 0;
    SET @aquacore_sql = CONCAT('SELECT COUNT(*) INTO @aquacore_meaningful ',
      'FROM `psutil` WHERE `', col, '` IS NOT NULL AND `', col, '` <> 0');
    PREPARE aquacore_stmt FROM @aquacore_sql;
    EXECUTE aquacore_stmt;
    DEALLOCATE PREPARE aquacore_stmt;
    IF @aquacore_meaningful = 0 THEN
      SET @aquacore_sql = CONCAT('ALTER TABLE `psutil` DROP COLUMN `', col, '`');
      PREPARE aquacore_stmt FROM @aquacore_sql;
      EXECUTE aquacore_stmt;
      DEALLOCATE PREPARE aquacore_stmt;
      SELECT col AS column_name, 'dropped (only NULL/zero values)' AS result;
    ELSE
      SELECT col AS column_name, @aquacore_meaningful AS nonzero_rows,
             'preserved for investigation' AS result;
    END IF;
  ELSE
    SELECT col AS column_name, 'already absent' AS result;
  END IF;
END//
DELIMITER ;

CALL `aquacore_drop_unused_psutil_if_empty`('scpufreq_min');
CALL `aquacore_drop_unused_psutil_if_empty`('scpufreq_max');
CALL `aquacore_drop_unused_psutil_if_empty`('cpu_thermal_high');
CALL `aquacore_drop_unused_psutil_if_empty`('cpu_thermal_crit');
CALL `aquacore_drop_unused_psutil_if_empty`('gpu_thermal_cur');
CALL `aquacore_drop_unused_psutil_if_empty`('gpu_thermal_high');
CALL `aquacore_drop_unused_psutil_if_empty`('gpu_thermal_crit');
CALL `aquacore_drop_unused_psutil_if_empty`('ve_thermal_cur');
DROP PROCEDURE `aquacore_drop_unused_psutil_if_empty`;
